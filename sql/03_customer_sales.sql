-- 9. First and second order date for repeat customers

WITH customer_orders AS (
    SELECT
        c.customer_unique_id,
        o.order_id,
        o.order_purchase_timestamp,
        ROW_NUMBER() OVER (
            PARTITION BY c.customer_unique_id
            ORDER BY o.order_purchase_timestamp
        ) AS order_number
    FROM customers c
    JOIN orders o
        ON c.customer_id = o.customer_id
)
SELECT
    customer_unique_id,
    MAX(CASE WHEN order_number = 1 THEN order_purchase_timestamp END)
        AS first_order_date,
    MAX(CASE WHEN order_number = 2 THEN order_purchase_timestamp END)
        AS second_order_date
FROM customer_orders
GROUP BY customer_unique_id
HAVING COUNT(*) > 1
ORDER BY first_order_date
LIMIT 20;


-- 10. Days between first and second purchase

WITH customer_orders AS (
    SELECT
        c.customer_unique_id,
        o.order_purchase_timestamp,
        ROW_NUMBER() OVER (
            PARTITION BY c.customer_unique_id
            ORDER BY o.order_purchase_timestamp
        ) AS order_number
    FROM customers c
    JOIN orders o
        ON c.customer_id = o.customer_id
),
repeat_customers AS (
    SELECT
        customer_unique_id,
        MAX(
            CASE
                WHEN order_number = 1
                THEN order_purchase_timestamp
            END
        ) AS first_order_date,
        MAX(
            CASE
                WHEN order_number = 2
                THEN order_purchase_timestamp
            END
        ) AS second_order_date
    FROM customer_orders
    GROUP BY customer_unique_id
    HAVING COUNT(*) > 1
)
SELECT
    ROUND(
        AVG(
            EXTRACT(
                EPOCH FROM (second_order_date - first_order_date)
            ) / 86400
        ),
        2
    ) AS avg_days_to_second_purchase
FROM repeat_customers;


-- 11. Distribution of time to second purchase

WITH customer_orders AS (
    SELECT
        c.customer_unique_id,
        o.order_purchase_timestamp,
        ROW_NUMBER() OVER (
            PARTITION BY c.customer_unique_id
            ORDER BY o.order_purchase_timestamp
        ) AS order_number
    FROM customers c
    JOIN orders o
        ON c.customer_id = o.customer_id
),
repeat_customers AS (
    SELECT
        customer_unique_id,
        MAX(
            CASE
                WHEN order_number = 1
                THEN order_purchase_timestamp
            END
        ) AS first_order_date,
        MAX(
            CASE
                WHEN order_number = 2
                THEN order_purchase_timestamp
            END
        ) AS second_order_date
    FROM customer_orders
    GROUP BY customer_unique_id
    HAVING COUNT(*) > 1
),
purchase_gap AS (
    SELECT
        customer_unique_id,
        EXTRACT(
            EPOCH FROM (
                second_order_date - first_order_date
            )
        ) / 86400 AS days_to_second_purchase
    FROM repeat_customers
),
purchase_ranges AS (
    SELECT
        customer_unique_id,
        days_to_second_purchase,
        CASE
            WHEN days_to_second_purchase <= 30
                THEN '0-30 days'
            WHEN days_to_second_purchase <= 90
                THEN '31-90 days'
            WHEN days_to_second_purchase <= 180
                THEN '91-180 days'
            WHEN days_to_second_purchase <= 365
                THEN '181-365 days'
            ELSE '365+ days'
        END AS purchase_range
    FROM purchase_gap
)
SELECT
    purchase_range,
    COUNT(*) AS customer_count
FROM purchase_ranges
GROUP BY purchase_range
ORDER BY
    CASE purchase_range
        WHEN '0-30 days' THEN 1
        WHEN '31-90 days' THEN 2
        WHEN '91-180 days' THEN 3
        WHEN '181-365 days' THEN 4
        WHEN '365+ days' THEN 5
    END;


-- 12. Median time to second purchase

WITH customer_orders AS (
    SELECT
        c.customer_unique_id,
        o.order_purchase_timestamp,
        ROW_NUMBER() OVER (
            PARTITION BY c.customer_unique_id
            ORDER BY o.order_purchase_timestamp
        ) AS order_number
    FROM customers c
    JOIN orders o
        ON c.customer_id = o.customer_id
),
repeat_customers AS (
    SELECT
        customer_unique_id,
        MAX(
            CASE
                WHEN order_number = 1
                THEN order_purchase_timestamp
            END
        ) AS first_order_date,
        MAX(
            CASE
                WHEN order_number = 2
                THEN order_purchase_timestamp
            END
        ) AS second_order_date
    FROM customer_orders
    GROUP BY customer_unique_id
    HAVING COUNT(*) > 1
)
SELECT
    ROUND(
        (
            PERCENTILE_CONT(0.5) WITHIN GROUP (
                ORDER BY EXTRACT(
                    EPOCH FROM (
                        second_order_date - first_order_date
                    )
                ) / 86400
            )
        )::numeric,
        2
    ) AS median_days_to_second_purchase
FROM repeat_customers;


