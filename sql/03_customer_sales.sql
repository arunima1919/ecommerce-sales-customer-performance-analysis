-- 17. Repeat rate by product category

WITH customer_category AS (
    SELECT DISTINCT
        c.customer_unique_id,
        p.product_category_name,
        CASE
            WHEN customer_order_counts.order_count > 1
            THEN 'Repeat customer'
            ELSE 'One-time customer'
        END AS customer_type
    FROM customers c
    JOIN orders o
        ON c.customer_id = o.customer_id
    JOIN order_items oi
        ON o.order_id = oi.order_id
    JOIN products p
        ON oi.product_id = p.product_id
    JOIN (
        SELECT
            c2.customer_unique_id,
            COUNT(DISTINCT o2.order_id) AS order_count
        FROM customers c2
        JOIN orders o2
            ON c2.customer_id = o2.customer_id
        GROUP BY c2.customer_unique_id
    ) customer_order_counts
        ON c.customer_unique_id = customer_order_counts.customer_unique_id
    WHERE p.product_category_name IS NOT NULL
)
SELECT
    COALESCE(
        ct.product_category_name_english,
        cc.product_category_name,
        'Unknown'
    ) AS category,
    COUNT(*) FILTER (
        WHERE customer_type = 'One-time customer'
    ) AS one_time_customers,
    COUNT(*) FILTER (
        WHERE customer_type = 'Repeat customer'
    ) AS repeat_customers,
    COUNT(*) AS total_customers,
    ROUND(
        100.0 * COUNT(*) FILTER (
            WHERE customer_type = 'Repeat customer'
        ) / COUNT(*),
        2
    ) AS repeat_rate
FROM customer_category cc
LEFT JOIN category_translation ct
    ON cc.product_category_name = ct.product_category_name
GROUP BY category
HAVING COUNT(*) >= 100
ORDER BY repeat_rate DESC;


